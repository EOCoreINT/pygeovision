"""Regenerate the per-task "Models" pages from the registry, the probe data and the hand-written family notes.

    PYTHONPATH=. python tools/generate_model_pages.py            # write
    PYTHONPATH=. python tools/generate_model_pages.py --check    # exit 1 if anything is out of date

Inputs:

* ``pygeovision.models.registry``       model names, tasks, families, weight sources
* ``docs/_data/model_probe.json``       measured parameter counts and tensor shapes (``tools/probe_models.py``)
* ``docs/_data/model_notes.yaml``       what each family is, when to pick it, how to modify it
* ``docs/_data/model_sections.yaml``    the introduction and choosing table of each page

Generated pages (never edit by hand; ``tests/test_reference_docs.py`` fails when they drift):
``segmentation/models.md``, ``classification/models.md``, ``detection/models.md``, ``change-detection/models.md``,
``lidar/models.md``, ``super-resolution/models.md``, ``vision-language/models.md`` and ``foundation-models/models.md``.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
NOTICE = "<!-- generated by tools/generate_model_pages.py - do not edit by hand -->\n"

STATUS = {
    "builds": "builds offline",
    "wrapper": "wrapper (downloads weights)",
    "error": "needs a network or an extra package",
    "listed_only": "listed, not buildable",
}


def _shape(v) -> str:
    """Render a probed shape, a list of shapes or a dict of shapes."""
    if v is None:
        return ""
    if isinstance(v, str):
        return v
    if isinstance(v, dict):
        return ", ".join(f"`{k}` {_shape(x)}" for k, x in v.items())
    if isinstance(v, list) and v and all(isinstance(i, int) for i in v):
        return "(" + ", ".join(str(i) for i in v) + ")"
    if isinstance(v, list):
        return " + ".join(_shape(i) for i in v)
    return str(v)


def _io(rec: dict) -> str:
    if rec.get("status") != "builds" or "input" not in rec:
        return ""
    if rec.get("forward_error"):
        return "forward failed in the probe"
    return f"{_shape(rec['input'])} → {_shape(rec.get('output'))}"


def _weights(spec) -> str:
    if spec.hf_id:
        return f"Hugging Face `{spec.hf_id}`"
    if spec.timm_id:
        return f"timm `{spec.timm_id}`"
    return "builder in this package"


def _family_block(task: str, family: str, specs: list, probe: dict, notes: dict) -> list[str]:
    n = notes.get(f"{task}/{family}")
    L: list[str] = []
    title = n["title"] if n else family
    L.append(f"## {title}\n")
    if not n:
        L.append("*No hand-written note exists for this family yet.*\n")
    else:
        L.append(n["what"].strip() + "\n")
        if n.get("built_with"):
            L.append(f"**Built with:** {n['built_with']}\n")
    L.append("| Model | Parameters (measured) | Input → output (measured) | Weights | Status |")
    L.append("|---|---:|---|---|---|")
    for s in specs:
        r = probe.get(s.name, {})
        pm = f"{r['params_m']} M" if "params_m" in r else f"≈{s.params_m} M (registry)" if s.params_m else ""
        L.append(f"| `{s.name}` | {pm} | {_io(r)} | {_weights(s)} | {STATUS.get(r.get('status'), 'not probed')} |")
    L.append("")
    msgs = [(s.name, probe.get(s.name, {}).get("message")) for s in specs if probe.get(s.name, {}).get("message")]
    for name, msg in msgs:
        L.append(f"`{name}` raises: *{msg.strip()}*\n")
    if n:
        if n.get("pick"):
            L.append("**Pick it when**\n")
            L += [f"- {x}" for x in n["pick"]] + [""]
        if n.get("avoid"):
            L.append("**Do not pick it when**\n")
            L += [f"- {x}" for x in n["avoid"]] + [""]
        if n.get("modify"):
            L.append("**Modify it**\n")
            L += [f"- {x}" for x in n["modify"]] + [""]
        if n.get("gotchas"):
            L.append("**Watch out**\n")
            L += [f"- {x}" for x in n["gotchas"]] + [""]
    return L


COMMON = """## Arguments every model takes

`get_model(name, num_classes=2, in_channels=4, pretrained=True, device=None, **kwargs)` is the one entry point for all
registered models.

| Argument | Meaning |
|---|---|
| `name` | A registry name from the tables above. An unknown name raises `KeyError`. |
| `num_classes` | Number of output classes. For detectors, the number of **object** types (the background is added for you). |
| `in_channels` | Number of input bands. The first layer is rebuilt; with `pretrained=True` the extra bands start from the mean of the RGB filters, which is a starting point to fine-tune, **not** a pretrained meaning. |
| `pretrained` | Load pretrained weights. If they cannot be loaded this raises `ModelLoadError`; it never quietly returns random weights. |
| `device` | Move the model to this device after building (`"cuda"`, `"cpu"`). |
| `allow_random_init` | `True` returns an architecture-only model, flagged `_pygeovision_is_random_init`, when weights cannot be loaded. Useful offline and in tests. |
| `img_size` | Chip size for models tied to one (ViT, Swin, UperNet). |

An entry that is registered but has no verified way to build raises `NotImplementedError` with the reason, instead of
returning a different network under that name.
"""


def page(key: str, sect: dict, specs_all: list, probe: dict, notes: dict) -> str:
    specs = [s for s in specs_all if s.task in sect["tasks"]]
    fams: dict[str, list] = {}
    for s in specs:
        fams.setdefault(s.family, []).append(s)
    n_build = sum(1 for s in specs if probe.get(s.name, {}).get("status") == "builds")
    L = [NOTICE, f"# {sect['title']}\n", sect["lead"].strip() + "\n"]
    L.append(f"The registry has **{len(specs)} entries** in {len(fams)} families here; **{n_build}** of them build "
             f"offline with `pretrained=False` in the probe that wrote the numbers on this page.\n")
    L.append("## Input and output\n")
    L.append(sect["io"].strip() + "\n")
    L.append("```{note}\nParameter counts and shapes in the tables are **measured** by building each model with "
             "`get_model(name, num_classes=3, in_channels=4, pretrained=False)` and running it on a small random tensor on "
             "the CPU (`tools/probe_models.py`). They are not copied from papers. Pretrained weights are downloaded on first "
             "use and need a network.\n```\n")
    L.append("## At a glance\n")
    L.append("| Model | Family | Parameters (measured) | Input → output (measured) | Status |")
    L.append("|---|---|---:|---|---|")
    for s in specs:
        r = probe.get(s.name, {})
        pm = f"{r['params_m']} M" if "params_m" in r else ""
        L.append(f"| `{s.name}` | {notes.get(f'{s.task}/{s.family}', {}).get('title', s.family)} | {pm} | {_io(r)} | "
                 f"{STATUS.get(r.get('status'), 'not probed')} |")
    L.append("")
    L.append("## Which one to choose\n")
    L.append("| You need… | Use |\n|---|---|")
    for a, b in sect["choose"]:
        L.append(f"| {a} | {b} |")
    L.append("")
    L.append("## Build one\n")
    L.append("```python\n" + sect["example"].strip("\n") + "\n```\n")
    for fam, ss in fams.items():
        task = ss[0].task
        L += _family_block(task, fam, ss, probe, notes)
    L.append(COMMON)
    L.append("## Related\n")
    L += [f"- {x}" for x in sect["related"]] + [""]
    return "\n".join(L)


def build() -> dict[Path, str]:
    from pygeovision.models import registry
    probe = json.loads((DOCS / "_data" / "model_probe.json").read_text(encoding="utf-8"))
    notes = yaml.safe_load((DOCS / "_data" / "model_notes.yaml").read_text(encoding="utf-8"))
    sections = yaml.safe_load((DOCS / "_data" / "model_sections.yaml").read_text(encoding="utf-8"))
    out = {}
    for key, sect in sections.items():
        out[DOCS / sect["out"]] = page(key, sect, list(registry._SPECS), probe, notes)
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for path, text in build().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if args.check and stale:
        print("out of date:", *[str(p.relative_to(ROOT)) for p in stale], sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
