"""Regenerate one documentation page per pipeline, plus the catalogue index.

    PYTHONPATH=. python tools/generate_pipeline_pages.py            # write
    PYTHONPATH=. python tools/generate_pipeline_pages.py --check    # exit 1 if a page is out of date

Everything that can come from the code does: the one-line description, the docstring, the ``run()`` arguments and
their defaults, the method, layers, limitations, "how to read it" notes and references of the pipeline's
``ReportSpec``, and an example run captured offline (``docs/_data/pipeline_examples.json``, synthetic data).
What only a person can say -- why you would run it, how to choose dates, how to read the numbers, what to do when
it fails -- lives in ``docs/_data/pipeline_notes.yaml``. ``tests/test_pipeline_pages.py`` fails when a page is stale
or a pipeline has no notes.
"""
from __future__ import annotations

import argparse
import inspect
import json
import shlex
import sys
import textwrap
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = DOCS / "pipelines" / "catalog"
NOTICE = "<!-- generated by tools/generate_pipeline_pages.py from the code and docs/_data/pipeline_notes.yaml - do not edit by hand -->\n"

# The topic groups of the documentation (sidebar and catalogue): title -> registry domains, in display order.
GROUPS: dict[str, list[str]] = {
    "Agriculture and vegetation": ["agriculture"],
    "Water and wetlands": ["water"],
    "Floods, fire and hazards": ["disaster", "fire", "geology"],
    "Land cover, forests and change": ["land", "forest", "forestry", "change"],
    "Cities and infrastructure": ["urban", "infrastructure"],
    "Energy and mining": ["energy", "mining"],
    "Climate, ice, terrain and ecology": ["climate", "cryosphere", "terrain", "coast", "ecology", "heritage"],
}
DOMAIN_TITLES = {dom: title for title, doms in GROUPS.items() for dom in doms}
DOMAIN_TITLES["other"] = "Other"

COMMON_STATS = {
    "valid_fraction": "Share of the study area that could be assessed (not cloud, shadow or outside the imagery). "
                      "Percentages and areas are computed over this part only.",
    "aoi_coverage_fraction": "Share of your box covered by the imagery that was used. Below 1.0 means part of the box "
                             "was never seen: do not quote totals for the whole box.",
    "product_note": "Free-text caveat about the data product, copied into the report.",
    "source_note": "Free-text caveat about the data source, copied into the report.",
}


def _load(name: str) -> dict:
    path = DOCS / "_data" / name
    return json.loads(path.read_text()) if name.endswith(".json") else yaml.safe_load(path.read_text())


def _fmt(v) -> str:
    if isinstance(v, float):
        return f"{v:.4g}"
    if isinstance(v, (dict, list)):
        return "…"
    return str(v)


def _params(cls) -> list[tuple[str, str, str]]:
    rows = []
    for name, p in inspect.signature(cls.run).parameters.items():
        if name in {"self", "bbox", "output_dir"} or p.kind is inspect.Parameter.VAR_KEYWORD:
            continue
        default = "required" if p.default is inspect.Parameter.empty else repr(p.default)
        rows.append((name, default, ""))
    return rows


def _channel_command(text: str) -> str:
    """The ``pygeovision channel`` command in a block that may also hold set-up lines (``data auth add``)."""
    text = text.replace("\\\n", " ")
    for line in text.splitlines():
        if "pygeovision channel" in line:
            return line.strip()
    return text.strip()


def _python_call(name: str, command: str) -> tuple[str, str]:
    """Turn the example command line into the equivalent Python call: (bbox literal, call)."""
    toks = shlex.split(_channel_command(command)) if command else []
    kw: list[str] = []
    bbox = "(-0.15, 51.47, -0.10, 51.52)"
    out_dir = "./out"
    i = 0
    while i < len(toks):
        t = toks[i]
        if t == "--bbox":
            bbox = "(" + ", ".join(toks[i + 1:i + 5]) + ")"; i += 4
        elif t in ("--output", "-o"):
            out_dir = toks[i + 1]; i += 1
        elif t == "--date":
            kw.append(f'date="{toks[i + 1]}"'); i += 1
        elif t == "--date-before":
            kw.append(f'date_before="{toks[i + 1]}"'); i += 1
        elif t == "--date-after":
            kw.append(f'date_after="{toks[i + 1]}"'); i += 1
        elif t == "--dates":
            kw.append("dates=[" + ", ".join(f'"{d}"' for d in toks[i + 1].split(",")) + "]"); i += 1
        elif t == "--checkpoint":
            kw.append('checkpoint="path/to/your_trained.pth"'); i += 1
        elif t == "--class-names":
            kw.append("class_names=[" + ", ".join(f'"{c.strip()}"' for c in toks[i + 1].split(",")) + "]"); i += 1
        elif t == "--param":
            k, _, v = toks[i + 1].partition("=")
            try:
                json.loads(v)
                kw.append(f"{k}={v}")
            except ValueError:
                if "," in v and all(x.strip().lstrip("-").isdigit() for x in v.split(",")):
                    kw.append(f"{k}=({', '.join(x.strip() for x in v.split(','))})")
                else:
                    kw.append(f'{k}="{v}"')
            i += 1
        i += 1
    args = ",\n    ".join(["bbox=bbox", *kw, f'output_dir="{out_dir}"'])
    return bbox, f'result = client.pipeline(\n    "{name}",\n    {args},\n)'


def _bullets(items) -> str:
    return "\n".join(f"- {x}" for x in items) + "\n"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    esc = lambda s: str(s).replace("|", "\\|").replace("\n", " ")  # noqa: E731
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


_SKIP_TUNE = {"date", "date_before", "date_after", "dates", "checkpoint", "model", "bands", "num_classes", "tile_size",
              "overlap", "crop_classes", "site", "reference", "source", "method", "start_year", "end_year", "baseline_year",
              "analysis_year", "pre_date", "post_date", "disaster_type", "providers", "resolution_m"}


def _tunable(cls):
    """The first numeric or boolean argument with a default that a variant would reasonably change, and an example value."""
    for pname, p in inspect.signature(cls.run).parameters.items():
        if pname in {"self", "bbox", "output_dir"} or pname in _SKIP_TUNE or p.kind is inspect.Parameter.VAR_KEYWORD:
            continue
        d = p.default
        if isinstance(d, bool):
            return pname, d, repr(not d)
        if isinstance(d, (int, float)) and not isinstance(d, bool):
            alt = (round(d * 1.5, 4) if isinstance(d, float) else d + 1) if d else (0.1 if isinstance(d, float) else 1)
            return pname, d, repr(alt)
    return None


def _modify_section(name: str, cls, modify: list) -> list[str]:
    src = Path(inspect.getsourcefile(cls)).resolve().relative_to(ROOT).as_posix()
    L = ["## Modify it\n",
         "Three levels, from least to most effort. Start at the first; most changes need nothing more.\n",
         "### 1. Change a setting\n",
         "Every argument in the table above is changed per run, with `--param NAME=VALUE` on the command line or `NAME=VALUE` in "
         "Python. The changes people make most with this pipeline:\n",
         _bullets(modify),
         "After any change, read the **parameters** block of `run_summary.json`: it records the values that were used, so a "
         "result can always be traced to its settings.\n",
         "### 2. Change where the data comes from, and what is written\n",
         "- **Providers.** `providers=[\"planetary_computer\"]` (CLI `--provider planetary_computer`) restricts the "
         "catalogues the pipeline searches; see [Providers](../../data/providers.md).\n"
         "- **Output.** `output_dir` (CLI `--output`) is the folder for the rasters, `run_summary.json` and `deliverables/`. "
         "Rebuild maps and reports from a finished run without re-downloading: [Rebuilding](../../reporting/rebuilding.md).\n"
         "- **Your own area.** A bounding box, or the true shape of an administrative area ([boundaries](../../data/boundaries.md)).\n",
         "### 3. Change the method (write a variant)\n",
         f"The pipeline is the class `{cls.__name__}` in `{src}`. To change its behaviour without editing the package, subclass "
         "it, give the subclass a new `name`, and override `run`. This changes the defaults of one run; the original is untouched:\n"]
    tun = _tunable(cls)
    cb = f"Base = pipeline_catalogue()[\"{name}\"]\n\n\nclass My{''.join(w.title() for w in name.split('_'))}(Base):\n    name = \"my_{name}\"          # a new name, so files and reports do not clash with the original\n\n"
    if tun:
        pn, d, alt = tun
        cb += (f"    def run(self, bbox, output_dir, **kwargs):\n        kwargs.setdefault(\"{pn}\", {alt})        # your default (the built-in one is {d!r})\n"
               "        return super().run(bbox, output_dir, **kwargs)\n")
    else:
        cb += ("    def run(self, bbox, output_dir, **kwargs):\n        result = super().run(bbox, output_dir, **kwargs)\n"
               "        if result.success:\n            print(\"written:\", result.output_path)      # post-process the output here\n"
               "        return result\n")
    L.append("```python\nfrom pygeovision import PyGeoVision\nfrom pygeovision.ai.pipelines import pipeline_catalogue\n\n" + cb
             + f"\nclient = PyGeoVision()\nresult = My{''.join(w.title() for w in name.split('_'))}(client).run(bbox, \"./variant\")   # plus the same date arguments as in Run it\n```\n")
    L.append("Calling `.run` on your class does not need any registration. To use it by name in `client.pipeline(...)`, register it "
             "in the process; to write a pipeline from scratch see [Write your own pipeline](../custom.md). The built-in "
             "`pygeovision channel` command runs only the built-in pipelines.\n")
    L.append("To change the numbers of the method itself (a threshold written in the code, not exposed as an argument), read "
             f"`{cls.__name__}.run` in `{src}`; the *How it works* section above lists the steps in the order the code takes them. "
             "Whatever you change, compare the new run with the old one ([comparing runs](../results.md#comparing-runs)) and validate the result "
             "against reference data before you use it ([validation](../../data/validation.md)).\n")
    return L


def page(name: str, cls, spec, ex: dict, notes: dict, modify: list) -> str:
    L: list[str] = [NOTICE, f"# `{name}`\n"]
    L.append(f"*{cls.description}*\n")
    kind = "Runs out of the box" if cls.kind == "ready" else "Needs your trained weights (`--checkpoint`)"
    L.append(f"**Topic:** {DOMAIN_TITLES.get(cls.domain, cls.domain)} · **Status:** {kind} · "
             f"**Tags:** {', '.join(f'`{t}`' for t in cls.tags)}\n")

    L.append("## The question it answers\n")
    L.append(f"> {spec.question}\n")
    L.append(notes["why"].strip() + "\n")

    L.append("## When to use it\n")
    L.append(_bullets(notes["use_when"]))
    if notes.get("not_for"):
        L.append("**Do not use it for:**\n")
        L.append(_bullets(notes["not_for"]))

    L.append("## How it works\n")
    doc = inspect.getdoc(cls) or cls.description
    L.append(doc.strip() + "\n")
    L.append("**Method, step by step**\n")
    L.append("\n".join(f"{i}. {m}" for i, m in enumerate(spec.method, 1)) + "\n")
    if notes.get("inputs"):
        L.append("**Inputs and accounts**\n")
        L.append(notes["inputs"].strip() + "\n")

    L.append("## Run it\n")
    L.append("```bash\n" + (notes.get("cli") or ex["command"]).strip() + "\n```\n")
    bbox_lit, call = _python_call(name, notes.get("cli") or ex["command"])
    L.append("```python\nfrom pygeovision import PyGeoVision\n\nclient = PyGeoVision()\nbbox = " + bbox_lit
             + "  # min_lon, min_lat, max_lon, max_lat\n" + call + "\n"
             "if not result.success:\n    raise SystemExit(result.error)\nprint(result.stats)\n```\n")
    if notes.get("python"):
        L.append(notes["python"].strip() + "\n")

    L.append("### Arguments\n")
    L.append("Every pipeline also takes `--bbox` and `--output`; see [common options](../index.md#common-options). "
             "`providers=[...]` (CLI `--provider`) restricts the data providers where the pipeline downloads imagery.\n")
    descr = notes.get("params") or {}
    rows = [[f"`{n}`", f"`{d}`" if d != "required" else "**required**", descr.get(n, "")] for n, d, _ in _params(cls)]
    if rows:
        L.append(_table(["Argument", "Default", "Meaning"], rows))
    else:
        L.append("This pipeline has no arguments besides the bounding box.\n")
    if notes.get("dates"):
        L.append("### Choosing dates and inputs\n")
        L.append(notes["dates"].strip() + "\n")

    L += _modify_section(name, cls, modify)

    L.append("## What you get\n")
    lay_rows = []
    for ly in spec.layers:
        what = "classes" if ly.kind == "classes" else "continuous values"
        lay_rows.append([f"`{ly.file}`", ly.title, what])
    L.append(_table(["File", "Layer", "Contents"], lay_rows))
    L.append("Written next to these: `run_summary.json` (every figure and parameter) and, unless switched off, a "
             "`deliverables/` folder with maps, GeoPackage/GeoJSON vectors and PDF, Word and Excel reports "
             "([Deliverables](../../reporting/index.md)). **255 in a class raster and NaN in a continuous raster mean "
             "no data**, never a class ([Core concepts](../../getting-started/concepts.md)).\n")
    if notes.get("outputs"):
        L.append(notes["outputs"].strip() + "\n")

    classes_layers = [ly for ly in ex["layers"] if ly.get("classes")]
    if classes_layers:
        L.append("**Classes in the example run**\n")
        rows = []
        for ly in classes_layers:
            for c in ly["classes"]:
                rows.append([f"`{ly['file']}`", c["value"], c["name"]])
        L.append(_table(["Raster", "Value", "Meaning"], rows))

    L.append("### Statistics\n")
    metric_notes = {m.key: (m.label, m.note) for m in spec.metrics}
    srows = []
    for k, v in ex["stats"].items():
        label, note = metric_notes.get(k, ("", ""))
        meaning = (notes.get("stats") or {}).get(k) or COMMON_STATS.get(k) or note or label
        srows.append([f"`{k}`", _fmt(v), meaning])
    L.append(_table(["`result.stats` key", "Example", "Meaning"], srows))

    L.append("## Example run\n")
    L.append("```{note}\nThe output below was produced by the **offline test harness** on a synthetic scene, to show the "
             "shape of a run. The numbers describe that synthetic data, not a place. Your figures come from your imagery.\n```\n")
    L.append("```text\n" + ex["console"] + "\n```\n")
    L.append("Files written (relative to the output folder):\n")
    L.append("```text\n" + "\n".join(ex["files"]) + "\n```\n")

    L.append("## Reading the results\n")
    if notes.get("interpret"):
        L.append(notes["interpret"].strip() + "\n")
    if spec.reading:
        L.append("**Notes from the report**\n")
        L.append(_bullets(spec.reading))
    if notes.get("workflow"):
        L.append("## Next steps with the output\n")
        L.append(notes["workflow"].strip() + "\n")

    L.append("## Limitations\n")
    L.append(_bullets(spec.limitations) if spec.limitations else "None beyond the general ones in [Core concepts](../../getting-started/concepts.md).\n")

    L.append("## What to do when…\n")
    rows = [[t["symptom"], t["fix"]] for t in notes["troubleshooting"]]
    rows.append(["`success=False` with \"No usable imagery\"", "Widen the date window; see the [troubleshooting guide](../../getting-started/troubleshooting.md)."])
    rows.append(["Warning about an unknown argument", "A misspelt `--param`: the message suggests the closest valid name."])
    L.append(_table(["Symptom", "What to do"], rows))

    if spec.references:
        L.append("## References\n")
        L.append(_bullets(spec.references))
    see = notes.get("see_also") or []
    if see:
        L.append("## See also\n")
        L.append(_bullets([f"[`{s}`]({s}.md)" if (OUT / f"{s}.md").exists() or s in KNOWN else s for s in see]))
    return "\n".join(L)


KNOWN: set[str] = set()


def _by_group(cat: dict) -> dict[str, list[tuple[str, object]]]:
    groups: dict[str, list] = {title: [] for title in GROUPS}
    for name, cls in sorted(cat.items()):
        title = DOMAIN_TITLES.get(cls.domain, "Other")
        groups.setdefault(title, []).append((name, cls))
    return {k: v for k, v in groups.items() if v}


def index(groups: dict[str, list[tuple[str, object]]]) -> str:
    n = sum(len(v) for v in groups.values())
    L = [NOTICE, "# Pipeline catalogue\n",
         f"All {n} pipelines, grouped by topic. Each page explains why you would run it, how, what comes out, how to read "
         "it, what to change and what to do when it fails. In the sidebar every topic is its own group.\n"]
    for title, items in groups.items():
        L.append(f"## {title}\n")
        rows = [[f"[`{nm}`]({nm}.md)", "ready" if c.kind == "ready" else "needs weights", c.description] for nm, c in items]
        L.append(_table(["Pipeline", "Status", "What it does"], rows))
    return "\n".join(L)


def sidebar(groups: dict[str, list[tuple[str, object]]]) -> str:
    """One toctree per topic, included from docs/index.md so each topic is a sidebar group of its own."""
    L = [NOTICE]
    for title, items in groups.items():
        L.append("```{toctree}\n:hidden:\n:maxdepth: 1\n:caption: Pipelines: " + title + "\n\n"
                 + "\n".join(f"pipelines/catalog/{nm}" for nm, _ in items) + "\n```\n")
    return "\n".join(L)


def build() -> dict[Path, str]:
    from pygeovision.ai.pipelines import pipeline_catalogue
    from pygeovision.reporting.specs import spec_for

    cat = pipeline_catalogue()
    examples = _load("pipeline_examples.json")
    notes = _load("pipeline_notes.yaml")
    modify = _load("pipeline_modify.yaml")
    KNOWN.update(cat)
    for fname, table in (("pipeline_notes.yaml", notes), ("pipeline_modify.yaml", modify)):
        missing = sorted(set(cat) - set(table))
        if missing:
            raise SystemExit(f"docs/_data/{fname} has no entry for: {', '.join(missing)}")
    out: dict[Path, str] = {}
    for name, cls in sorted(cat.items()):
        out[OUT / f"{name}.md"] = page(name, cls, spec_for(name), examples[name], notes[name], modify[name])
    groups = _by_group(cat)
    out[OUT / "index.md"] = index(groups)
    out[DOCS / "pipelines" / "_sidebar.md"] = sidebar(groups)
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for path, text in build().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("out of date:", *[str(p.relative_to(ROOT)) for p in stale], sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
