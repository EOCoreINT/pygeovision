def model_status(spec) -> tuple[str, str]:
    """(short code, explanation) of what ``get_model(spec.name)`` does."""
    d = spec.description
    if "NotImplementedError" in d or "no verified" in d:
        return "listed only", "Registered so you can find it; `get_model` raises `NotImplementedError`."
    if spec.family == "prithvi":
        return "pretrained only", "No architecture-only build: needs the Hub download (or `allow_random_init=True`)."
    if spec.family == "dofa":
        return "needs torchgeo", "Built through `torchgeo` (`pip install torchgeo`)."
    if spec.name in ("grounding-dino", "mask2former-swin-t", "mask2former-swin-b"):
        return "needs Hub", "Even an untrained model needs its config from the Hugging Face Hub."
    if spec.name in ("tessera", "alphaearth"):
        return "embeddings", "Precomputed embedding product, not a network you train."
    if spec.family in ("clip", "moondream", "sam", "sam2"):
        return "wrapper", "A wrapper object; weights are loaded when you first use it."
    return "builds", "Builds with no network; `pretrained=True` fetches weights."


def models_catalog_page() -> str:
    from pygeovision.ai.models.registry import registry as legacy
    from pygeovision.ai.models.zoo import model_zoo
    from pygeovision.models.registry import _REGISTRY

    by_task: dict[str, list] = {}
    for spec in _REGISTRY.values():
        by_task.setdefault(spec.task, []).append(spec)

    out = [NOTICE, "# Model catalogue\n"]
    out.append(
        f"Everything the model registries contain, generated from the code. PyGeoVision has **three** lists of models "
        f"that serve different purposes ([how they relate](registry.md)); this page shows each.\n"
    )
    out.append("| List | Entries | What it is | Browse with |\n|---|---|---|---|")
    out.append(f"| [Native registry](#native-registry) | {len(_REGISTRY)} | Architectures you can build with `get_model` | `pygeovision models list` |")
    out.append(f"| [Legacy engine registry](#legacy-engine-registry) | {len(legacy.list_models())} | The names the `infer`, `ai` and `channel` commands load your checkpoint into | `pygeovision ai-models list` |")
    out.append(f"| [Model zoo](#model-zoo) | {len(model_zoo)} | A descriptive catalogue; nothing is built from it | `pygeovision zoo list` |\n")

    out.append("(native-registry)=\n## Native registry\n")
    out.append(
        "Names use hyphens (`unet-r50`, `segformer-b2`). Build one with `get_model(name, num_classes=, in_channels=, "
        "pretrained=)`. The **Build** column says what to expect:\n\n"
        "| Build | Meaning |\n|---|---|\n"
        "| builds | Constructs with no network. `pretrained=True` additionally downloads weights |\n"
        "| wrapper | Returns a helper object that loads its weights on first use |\n"
        "| pretrained only | Cannot be built without its pretrained weights |\n"
        "| needs Hub / needs torchgeo | Needs a network connection or an extra package even for an untrained model |\n"
        "| embeddings | A precomputed data product, not a trainable network |\n"
        "| listed only | Visible for discovery; `get_model` raises `NotImplementedError` and says why |\n\n"
        "**Parameters (M)** are the published size of the architecture, not a measurement of the object built here "
        "(sizes change with your band and class counts).\n"
    )
    order = [t for t in TASK_TITLES if t in by_task] + [t for t in by_task if t not in TASK_TITLES]
    for task in order:
        specs = by_task[task]
        out.append(f"### {TASK_TITLES.get(task, task)} ({len(specs)})\n")
        out.append(TASK_BLURB.get(task, "") + "\n")
        show_pre = task == "foundation"
        head = "| Name | Family | Parameters (M) | Weights from |" + (" Pretrained on |" if show_pre else "") + " Build |"
        out.append(head)
        out.append("|---|---|---:|---|" + ("---|" if show_pre else "") + "---|")
        for sp in specs:
            src = f"`{sp.hf_id}`" if sp.hf_id else (f"timm `{sp.timm_id}`" if sp.timm_id else "-")
            code, _ = model_status(sp)
            pre = f" {sp.pretrained_on if code != 'listed only' else '-'} |" if show_pre else ""
            out.append(f"| `{sp.name}` | {sp.family} | {sp.params_m:g} | {src} |{pre} {code} |")
        notes = [sp for sp in specs if model_status(sp)[0] in ("listed only",)]
        if notes:
            out.append("\nListed only:")
            for sp in notes:
                out.append(f"- `{sp.name}`: {sp.description.split(' -- ', 1)[-1] if ' -- ' in sp.description else sp.description}")
        out.append("")

    out.append("(legacy-engine-registry)=\n## Legacy engine registry\n")
    out.append(
        "These 14 names are what `--model` accepts in `pygeovision infer ...`, `pygeovision ai infer|detect|segment`, "
        "`pygeovision channel ... --checkpoint` and YAML `infer` steps. Names use underscores. "
        "A name that is not here falls through to the native registry, so `--model unet-r50` also works.\n"
    )
    out.append("| Name | Task | Architecture | Bands | Pretrained weights | Description |\n|---|---|---|---:|---|---|")
    for m in sorted(legacy.list_models(), key=lambda m: (m.task, m.name)):
        bands = "any" if m.input_bands == -1 else m.input_bands
        out.append(f"| `{m.name}` | {m.task} | {m.architecture} | {bands} | {'yes' if m.pretrained_available else 'no'} | {m.description} |")
    out.append("\n**Bands** is the default input band count; every model is built for the band count you pass.\n")

    out.append("(model-zoo)=\n## Model zoo\n")
    tasks: dict[str, int] = {}
    for m in model_zoo._models:
        tasks[m.task] = tasks.get(m.task, 0) + 1
    hf = sum(1 for m in model_zoo._models if m.hf_model_id)
    out.append(
        f"The zoo describes {len(model_zoo)} architectures (parameter counts, tags, typical uses). It is a *catalogue*: "
        f"`pygeovision zoo ...` helps you read about models, and nothing in the zoo builds a model. Only {hf} entries name a "
        f"Hugging Face checkpoint. To build a model, take the name from the native or legacy registry.\n"
    )
    out.append("| Task | Entries |\n|---|---:|")
    for t, n in sorted(tasks.items()):
        out.append(f"| {t} | {n} |")
    out.append("")
    return "\n".join(out)

