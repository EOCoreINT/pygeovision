def build() -> dict[Path, str]:
    out: dict[Path, str] = {DOCS / "data" / "providers.md": providers_page(),
                            DOCS / "models" / "catalog.md": models_catalog_page()}
    for name, text in cli_pages().items():
        out[DOCS / "reference" / "cli" / name] = text
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for path, text in build().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.check and stale:
        print("out of date:", *[str(p.relative_to(ROOT)) for p in stale], sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
