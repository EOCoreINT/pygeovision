"""Regenerate the pipeline reference pages from the live classes.

    python tools/generate_pipeline_docs.py

Writes docs/pipelines/{ready,needs-weights,removed}.md and
docs/reference/pipeline-catalog.md. The pages are built from each
pipeline's own docstring and ``run()`` signature, so they cannot drift
from the code. ``tests/test_pipeline_docs.py`` fails when they do.
"""
from __future__ import annotations

import inspect
from pathlib import Path

from pygeovision.ai.pipelines import pipeline_catalogue
from pygeovision.ai.pipelines.removed import REMOVED_PIPELINES

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
NOTICE = "<!-- generated by tools/generate_pipeline_docs.py - do not edit by hand -->\n"
SKIP = {"self", "bbox", "output_dir", "kwargs"}


def _params(cls) -> list[tuple[str, str]]:
    rows = []
    for name, p in inspect.signature(cls.run).parameters.items():
        if name in SKIP or p.kind is inspect.Parameter.VAR_KEYWORD:
            continue
        default = "required" if p.default is inspect.Parameter.empty else f"`{p.default!r}`"
        rows.append((name, default))
    return rows


def _section(name: str, cls) -> str:
    doc = inspect.getdoc(cls) or cls.description
    lines = [f"## `{name}`", "", f"*{cls.description}*  ", f"Topic: {cls.domain} · Kind: **{cls.kind}**", "",
             doc, ""]
    params = _params(cls)
    if params:
        lines += ["| Argument | Default |", "|---|---|"] + [f"| `{n}` | {d} |" for n, d in params] + [""]
    lines += ["```python", f'result = client.pipeline("{name}", bbox=bbox, output_dir="out"'
              + (", ..." if params else "") + ")", "```", ""]
    return "\n".join(lines)


def _page(title: str, intro: str, kind: str) -> str:
    cat = pipeline_catalogue()
    names = [n for n, c in sorted(cat.items()) if c.kind == kind]
    body = "\n".join(_section(n, cat[n]) for n in names)
    return f"{NOTICE}# {title}\n\n{intro}\n\n{len(names)} pipelines.\n\n{body}"


def main() -> None:
    (DOCS / "pipelines").mkdir(exist_ok=True)
    (DOCS / "pipelines" / "ready.md").write_text(_page(
        "Pipelines that run out of the box",
        "These need nothing but a bounding box and dates. Each is a documented index, "
        "a terrain product, or a published reference map. Cloud- and shadow-masked "
        "pixels are written as nodata and excluded from every percentage and area.",
        "ready"))
    (DOCS / "pipelines" / "needs-weights.md").write_text(_page(
        "Pipelines that need your trained weights",
        "These run a neural network. PyGeoVision ships no trained weights for them, "
        "so they refuse to run (before downloading any imagery) unless you pass "
        "`checkpoint=` pointing at a model you trained, for example with `GeoTrainer`. "
        "The checkpoint is loaded strictly: a class or band-count mismatch is an error, "
        "never a silent fallback.",
        "needs_weights"))
    removed = [f"{NOTICE}# Pipelines removed before launch\n",
               f"{len(REMOVED_PIPELINES)} of the original 49 pipelines were removed because they could not "
               "produce a correct result. Asking for one raises an error that quotes the reason below.\n"]
    for n, why in sorted(REMOVED_PIPELINES.items()):
        removed.append(f"- **`{n}`**: {why.strip()}")
    (DOCS / "pipelines" / "removed.md").write_text("\n".join(removed) + "\n")

    cat = pipeline_catalogue()
    rows = ["| Pipeline | Kind | What it does |", "|---|---|---|"]
    rows += [f"| `{n}` | {c.kind.replace('_', ' ')} | {c.description} |" for n, c in sorted(cat.items())]
    (DOCS / "reference" / "pipeline-catalog.md").write_text(
        f"{NOTICE}# Pipeline Catalog (Quick Reference)\n\n"
        f"{len(cat)} pipelines. `ready` runs out of the box; `needs weights` requires "
        "`checkpoint=` (your trained model). Removed pipelines are listed on "
        "[this page](../pipelines/removed.md).\n\n" + "\n".join(rows) + "\n")


if __name__ == "__main__":
    main()
