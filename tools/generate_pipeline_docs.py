"""Regenerate the page that lists the removed pipelines.

    python tools/generate_pipeline_docs.py

Writes docs/pipelines/removed.md from ``REMOVED_PIPELINES``, so the reasons shown cannot drift from the ones the
error message quotes. The per-pipeline pages come from ``tools/generate_pipeline_pages.py``.
``tests/test_pipeline_docs.py`` fails when either is out of date.
"""
from __future__ import annotations

from pathlib import Path

from pygeovision.ai.pipelines.removed import REMOVED_PIPELINES

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
NOTICE = "<!-- generated by tools/generate_pipeline_docs.py - do not edit by hand -->\n"


def main() -> None:
    (DOCS / "pipelines").mkdir(exist_ok=True)
    removed = [f"{NOTICE}# Removed pipelines\n",
               f"{len(REMOVED_PIPELINES)} of the original 49 pipelines stay removed because they cannot "
               "produce a correct result today. (Three others, `landcover_change`, `road_extraction` and "
               "`landslide_detection`, came back once a real implementation existed.) "
               "Asking for one raises an error that quotes the reason below.\n"]
    for n, why in sorted(REMOVED_PIPELINES.items()):
        removed.append(f"- **`{n}`**: {why.strip()}")
    (DOCS / "pipelines" / "removed.md").write_text("\n".join(removed) + "\n")


if __name__ == "__main__":
    main()
