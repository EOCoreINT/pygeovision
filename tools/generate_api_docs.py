"""Regenerate the Python API reference pages from the source code.

    PYTHONPATH=. python tools/generate_api_docs.py            # write
    PYTHONPATH=. python tools/generate_api_docs.py --check    # exit 1 if anything is out of date

The list of pages and modules is ``docs/_data/api_pages.yaml``. The public classes and functions of each module are found by
*reading the source* (``ast``), not by importing it, so the generator needs no heavy dependency and produces the same output on
every machine. Each page lists a summary table (name, kind, first line of the docstring) and then ``autodoc`` directives, so
Sphinx renders the full signatures and docstrings. ``tests/test_reference_docs.py`` fails when a page is stale or when a public
name exported by a package is missing from every page.
"""
from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = DOCS / "reference" / "api"
NOTICE = "<!-- generated by tools/generate_api_docs.py from docs/_data/api_pages.yaml and the source - do not edit by hand -->\n"


def module_file(dotted: str) -> Path:
    rel = Path(*dotted.split("."))
    for cand in (ROOT / rel.with_suffix(".py"), ROOT / rel / "__init__.py"):
        if cand.exists():
            return cand
    raise SystemExit(f"api_pages.yaml names a module that does not exist: {dotted}")


def _all_of(tree: ast.Module) -> list[str] | None:
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "__all__" for t in node.targets):
            try:
                return list(ast.literal_eval(node.value))
            except (ValueError, SyntaxError):
                return None
    return None


def parse(dotted: str):
    path = module_file(dotted)
    tree = ast.parse(path.read_text(encoding="utf-8"))
    defs = {}
    for node in tree.body:
        if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            defs[node.name] = node
    return tree, defs


def _first_line(node) -> str:
    doc = ast.get_docstring(node) or ""
    para = doc.strip().split("\n\n")[0] if doc else ""
    line = " ".join(para.split())
    if len(line) > 160:
        line = line[:157].rsplit(" ", 1)[0] + "…"
    return line.replace("|", "\\|")


def public_names(dotted: str, explicit: list[str] | None = None) -> list[tuple[str, str, str]]:
    """(name, kind, summary) of the public classes and functions defined in the module, in source order."""
    tree, defs = parse(dotted)
    if explicit is not None:
        missing = [n for n in explicit if n not in defs]
        if missing:
            raise SystemExit(f"{dotted} has no top-level definition named {missing}")
        names = explicit
    else:
        exported = _all_of(tree)
        names = [n for n in defs if not n.startswith("_") and (exported is None or n in exported)]
    return [(n, "class" if isinstance(defs[n], ast.ClassDef) else "function", _first_line(defs[n])) for n in names]


def module_summary(dotted: str) -> str:
    tree, _ = parse(dotted)
    doc = ast.get_docstring(tree) or ""
    return doc.strip().split("\n\n")[0].replace("\n", " ") if doc else ""


def page(spec: dict) -> str:
    L = [NOTICE, f"# {spec['title']}\n"]
    if spec.get("intro"):
        L.append(spec["intro"].strip() + "\n")
    if spec.get("explained_in"):
        L.append("**Explained in:** " + " · ".join(spec["explained_in"]) + "\n")
    mods = []
    for m in spec["modules"]:
        mods.append(m if isinstance(m, dict) else {"module": m})
    total = 0
    body: list[str] = []
    for m in mods:
        dotted = m["module"]
        names = public_names(dotted, m.get("names"))
        if not names:
            continue
        total += len(names)
        body.append(f"## `{dotted}`\n")
        summary = module_summary(dotted)
        if summary:
            body.append(summary + "\n")
        body.append("| Name | Kind | What it is |\n|---|---|---|")
        for n, kind, line in names:
            body.append(f"| `{n}` | {kind} | {line} |")
        body.append("")
        rst = ["```{eval-rst}"]
        for n, kind, _ in names:
            directive = "autoclass" if kind == "class" else "autofunction"
            rst.append(f".. py:currentmodule:: {dotted}\n")
            rst.append(f".. {directive}:: {dotted}.{n}")
            if kind == "class":
                rst.append("   :members:")
            rst.append("")
        rst.append("```\n")
        body.append("\n".join(rst))
    L.append(f"This page documents **{total} public classes and functions** in {len(mods)} modules.\n")
    L += body
    return "\n".join(L)


def build() -> dict[Path, str]:
    pages = yaml.safe_load((DOCS / "_data" / "api_pages.yaml").read_text(encoding="utf-8"))
    out: dict[Path, str] = {}
    for spec in pages:
        out[OUT / f"{spec['slug']}.md"] = page(spec)
    entries = "\n".join(f"reference/api/{s['slug']}" for s in pages)
    out[OUT / "_sidebar.md"] = (NOTICE + "\n```{toctree}\n:hidden:\n:maxdepth: 1\n:caption: Python API\n\n"
                                "reference/python-api\n" + entries + "\n```\n")
    rows = ["| Page | What it documents |", "|---|---|"]  # this table is included by reference/python-api.md, so links start at api/
    for s in pages:
        rows.append(f"| [{s['title']}](api/{s['slug']}.md) | {s['summary']} |")
    out[OUT / "_index_table.md"] = NOTICE + "\n".join(rows) + "\n"
    return out


def documented_names() -> set[str]:
    names: set[str] = set()
    for spec in yaml.safe_load((DOCS / "_data" / "api_pages.yaml").read_text(encoding="utf-8")):
        for m in spec["modules"]:
            m = m if isinstance(m, dict) else {"module": m}
            names.update(n for n, _, _ in public_names(m["module"], m.get("names")))
    return names


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for path, text in build().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if args.check and stale:
        print("out of date:", *[str(p.relative_to(ROOT)) for p in stale], sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
